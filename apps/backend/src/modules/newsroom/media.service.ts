import { ConflictException, Inject, Injectable, Logger, NotFoundException } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'node:crypto';
import type { Readable } from 'node:stream';
import { DataSource, type EntityManager } from 'typeorm';
import { requirePermission, type Actor } from '../../common/access/permissions.js';
import { AiUnavailableException } from '../../common/ai/ai-provider.js';
import { AiService } from '../../common/ai/ai.service.js';
import { imagePrompt } from '../../common/ai/prompts.js';
import { audit } from '../../common/audit/audit.js';
import { i18nString, type I18nString } from '../../common/i18n/i18n-string.js';
import { MEDIA_VARIANT_NAMES, mediaVariantKey, mediaVariantMimeType, renderMediaImage, type MediaVariant } from '../../common/storage/media-images.js';
import { mediaFolder } from '../../common/storage/storage-layout.js';
import { StorageService } from '../../common/storage/storage.service.js';

export const MEDIA_PAGE_SIZE = 24;
const escapeLike = (value: string) => value.replace(/[\\%_]/g, '\\$&');

interface MediaRow {
  id: string; source: 'upload' | 'ai'; width: number; height: number; color: string; bytes: string; title: string; alt: I18nString;
  caption: I18nString; credit: string; ai_prompt: string | null; created_at: Date; created_by_name: string | null; usage?: number; total?: number;
}

export interface MediaMetadata { title?: string; alt?: unknown; caption?: unknown; credit?: string }

/**
 * The media library: every image news use (covers and images inside the body), uploaded or generated by the AI. Each
 * is stored as renditions only (`media-images.ts`), served publicly by id and size through the frontend's relay, and
 * described in both languages (alternative text and caption) plus credit.
 */
@Injectable()
export class MediaService {
  private readonly logger = new Logger(MediaService.name);

  constructor(
    @Inject(DataSource) private readonly database: DataSource,
    @Inject(StorageService) private readonly storage: StorageService,
    @Inject(ConfigService) private readonly config: ConfigService,
    @Inject(AiService) private readonly ai: AiService,
  ) {}

  private get maxBytes(): number {
    return (this.config.get<number>('UPLOAD_MAX_MB') ?? 15) * 1024 * 1024;
  }

  async list(actor: Actor, query: { search?: string; source?: 'upload' | 'ai'; page?: number }) {
    requirePermission(actor, 'news:read', 'media:manage');
    const page = Math.max(1, query.page ?? 1);
    const conditions: string[] = [];
    const parameters: unknown[] = [];
    if (query.search?.trim()) {
      parameters.push(`%${escapeLike(query.search.trim())}%`);
      conditions.push(`public.pmn_fold(m.title || ' ' || coalesce(m.alt ->> 'pt', '') || ' ' || coalesce(m.alt ->> 'en', '') || ' ' || m.credit) LIKE public.pmn_fold($${parameters.length})`);
    }
    if (query.source) {
      parameters.push(query.source);
      conditions.push(`m.source = $${parameters.length}`);
    }
    const rows: MediaRow[] = await this.database.query(`SELECT m.*, u.name AS created_by_name, count(*) OVER ()::int AS total,
      ${this.usage('m')} AS usage FROM public.media m LEFT JOIN public.users u ON u.id = m.created_by
      ${conditions.length ? `WHERE ${conditions.join(' AND ')}` : ''}
      ORDER BY m.created_at DESC, m.id LIMIT ${MEDIA_PAGE_SIZE} OFFSET ${(page - 1) * MEDIA_PAGE_SIZE}`, parameters);
    return { items: rows.map((row) => this.view(row)), total: rows[0]?.total ?? 0, page, pageSize: MEDIA_PAGE_SIZE };
  }

  async get(actor: Actor, id: string) {
    requirePermission(actor, 'news:read', 'media:manage');
    return this.view(await this.row(this.database.manager, id));
  }

  /** Several items at once, by id, in no particular order: what a body's images need to render. Public. */
  async describe(ids: readonly string[], manager: EntityManager = this.database.manager) {
    if (!ids.length) return [];
    const rows: MediaRow[] = await manager.query(`SELECT m.*, NULL AS created_by_name FROM public.media m WHERE m.id = ANY($1::uuid[])`, [ids]);
    return rows.map((row) => this.publicView(row));
  }

  async upload(actor: Actor, file: Buffer, metadata: MediaMetadata) {
    requirePermission(actor, 'media:manage');
    const rendered = await renderMediaImage(file, this.maxBytes);
    return this.store(actor, rendered, 'upload', metadata, null);
  }

  /**
   * Generates an image with the AI and keeps it in the library like an upload, marked as generated (the site labels
   * it so). The prompt is kept with the item, so the newsroom knows how it was made.
   */
  async generate(actor: Actor, input: { prompt: string } & MediaMetadata) {
    requirePermission(actor, 'media:manage');
    requirePermission(actor, 'ai:use');
    const context = await this.ai.context();
    if (!context.images) throw new AiUnavailableException('ai_images_unavailable');
    const image = await context.provider.image({ prompt: imagePrompt(input.prompt), signal: AbortSignal.timeout(120_000) });
    const rendered = await renderMediaImage(image.data, 40 * 1024 * 1024);
    return this.store(actor, rendered, 'ai', { ...input, credit: input.credit || (context.provider.generative ? 'Imagem gerada por IA' : 'Ilustração provisória') }, input.prompt);
  }

  private async store(actor: Actor, rendered: Awaited<ReturnType<typeof renderMediaImage>>, source: 'upload' | 'ai', metadata: MediaMetadata, prompt: string | null) {
    const id = randomUUID();
    const keys: string[] = [];
    try {
      for (const variant of MEDIA_VARIANT_NAMES) {
        const key = mediaVariantKey(id, variant);
        await this.storage.uploadRawObject(key, rendered.variants[variant], mediaVariantMimeType(variant), rendered.variants[variant].length);
        keys.push(key);
      }
      return await this.database.transaction(async (manager) => {
        await manager.query(`INSERT INTO public.media (id, source, width, height, color, bytes, title, alt, caption, credit, ai_prompt, created_by)
          VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb, $9::jsonb, $10, $11, $12)`, [
          id, source, rendered.width, rendered.height, rendered.color, rendered.bytes, (metadata.title ?? '').trim().slice(0, 200),
          JSON.stringify(i18nString(metadata.alt, { maxLength: 300, required: false })),
          JSON.stringify(i18nString(metadata.caption, { maxLength: 500, required: false })), (metadata.credit ?? '').trim().slice(0, 160),
          prompt?.slice(0, 4000) ?? null, actor.userId,
        ]);
        await audit(manager, { actorId: actor.userId, action: source === 'ai' ? 'media.generated' : 'media.uploaded', resourceType: 'media', resourceId: id });
        return this.view(await this.row(manager, id));
      });
    } catch (error) {
      await this.storage.deleteObjects(keys).catch(() => undefined);
      throw error;
    }
  }

  async update(actor: Actor, id: string, metadata: MediaMetadata) {
    requirePermission(actor, 'media:manage');
    return this.database.transaction(async (manager) => {
      const current = await this.row(manager, id);
      await manager.query(`UPDATE public.media SET title = $2, alt = $3::jsonb, caption = $4::jsonb, credit = $5, updated_at = now() WHERE id = $1`, [
        id, metadata.title === undefined ? current.title : metadata.title.trim().slice(0, 200),
        JSON.stringify(metadata.alt === undefined ? current.alt : i18nString(metadata.alt, { maxLength: 300, required: false })),
        JSON.stringify(metadata.caption === undefined ? current.caption : i18nString(metadata.caption, { maxLength: 500, required: false })),
        metadata.credit === undefined ? current.credit : metadata.credit.trim().slice(0, 160),
      ]);
      await audit(manager, { actorId: actor.userId, action: 'media.updated', resourceType: 'media', resourceId: id });
      return this.view(await this.row(manager, id));
    });
  }

  /** An image still used by a news item (cover or body) is never deleted: the article would lose it. */
  async remove(actor: Actor, id: string) {
    requirePermission(actor, 'media:manage');
    await this.database.transaction(async (manager) => {
      const row = await this.row(manager, id);
      if (row.usage) throw new ConflictException({ statusCode: 409, message: 'The image is in use', code: 'media_in_use', usage: row.usage });
      await manager.query('DELETE FROM public.media WHERE id = $1', [id]);
      await audit(manager, { actorId: actor.userId, action: 'media.deleted', resourceType: 'media', resourceId: id });
    });
    await this.storage.deletePrefix(mediaFolder(id)).catch(() => this.logger.warn('A deleted image left files in the store'));
  }

  /** One rendition, for the public relay. Only items that exist are served. */
  async stream(id: string, variant: MediaVariant): Promise<{ stream: Readable; mimeType: string }> {
    const [row]: unknown[] = await this.database.query('SELECT 1 FROM public.media WHERE id = $1', [id]);
    if (!row) throw new NotFoundException();
    return { stream: await this.storage.getObjectStream(mediaVariantKey(id, variant)), mimeType: mediaVariantMimeType(variant) };
  }

  /** How many news items use an image, as cover or inside a body. */
  private usage(alias: string): string {
    return `(SELECT count(*)::int FROM public.news n WHERE n.cover_media_id = ${alias}.id
      OR position('/media/' || ${alias}.id::text || '/' IN coalesce(n.body ->> 'pt', '') || coalesce(n.body ->> 'en', '')) > 0)`;
  }

  private async row(manager: EntityManager, id: string): Promise<MediaRow> {
    const [row]: MediaRow[] = await manager.query(`SELECT m.*, u.name AS created_by_name, ${this.usage('m')} AS usage
      FROM public.media m LEFT JOIN public.users u ON u.id = m.created_by WHERE m.id = $1`, [id]);
    if (!row) throw new NotFoundException();
    return row;
  }

  publicView(row: MediaRow) {
    return { id: row.id, source: row.source, width: row.width, height: row.height, color: row.color, alt: row.alt, caption: row.caption, credit: row.credit };
  }

  view(row: MediaRow) {
    return {
      ...this.publicView(row), title: row.title, bytes: Number(row.bytes), aiPrompt: row.ai_prompt, createdAt: row.created_at.toISOString(),
      createdBy: row.created_by_name, usage: row.usage ?? 0,
    };
  }
}
