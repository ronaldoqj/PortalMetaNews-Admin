type Params = PageProps<"/[locale]/site/news/[slug]">["params"];

/** The article of the address, or the address of the same article in this language when the slug is the other language's. */
async function resolve(params: Params): Promise<{ article: Article; locale: AppLocale } | null> {
  const { locale: value, slug: raw } = await params;
  const locale = value as AppLocale;
  const slug = slugParameter(raw);
  if (!slug) return null;
  const article = await getArticle(locale, slug);
  if (article) return { article, locale };
  // The language switch keeps the slug: a slug of the other language leads to this language's version, or its home.
  const other = await getArticle(otherLocale(locale), slug);
  if (other) {
    const own = other.alternates[locale];
    redirect(own ? getPathname({ locale, href: { pathname: "/site/news/[slug]", params: { slug: own } } }) : getPathname({ locale, href: "/site" }));
  }
  return null;
}

const hrefsOf = (article: Article) => Object.fromEntries(routing.locales.flatMap((locale) => article.alternates[locale]
  ? [[locale, { pathname: "/site/news/[slug]", params: { slug: article.alternates[locale]! } } as const]] : []));

export async function generateMetadata({ params }: PageProps<"/[locale]/site/news/[slug]">): Promise<Metadata> {
  const resolved = await resolve(params);
  if (!resolved) return {};
  const { article, locale } = resolved;
  return pageMetadata({
    locale, title: article.seo.title, description: article.seo.description, hrefs: hrefsOf(article),
    image: article.cover ? { url: `/media/${article.cover.id}/og`, width: 1200, height: 630, alt: article.cover.alt } : undefined,
    article: {
      publishedTime: article.publishedAt, modifiedTime: article.updatedAt, section: article.category?.name,
      tags: article.tags.map((tag) => tag.name), authors: article.author ? [await pageUrl(locale, { pathname: "/site/author/[id]", params: { id: article.author.id } })] : [],
    },
  });
}

/**
 * A news article: section, title, subtitle, byline with dates and reading time, sharing, the cover with its caption and
 * credit (marked when generated by AI), the body, tags, the author and related news. Structured data (`NewsArticle`)
 * describes it to search engines; one view is counted after the page shows.
 */
export default async function ArticlePage({ params }: PageProps<"/[locale]/site/news/[slug]">) {
  const resolved = await resolve(params);
  if (!resolved) return <PageNotFound />;
  const { article, locale } = resolved;
  const [translate, format, { site, assets }] = await Promise.all([getTranslations("Article"), getFormatter(), getRequestBranding()]);
  const url = await pageUrl(locale, { pathname: "/site/news/[slug]", params: { slug: article.slug } });
  const siteName = site?.siteName ?? "Portal Meta News";
  const date = (iso: string) => format.dateTime(new Date(iso), { day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit" });
  const updated = new Date(article.updatedAt).getTime() - new Date(article.publishedAt).getTime() > 5 * 60 * 1000;
  const cover = article.cover;
  const sources = cover ? mediaSources(cover.id) : null;
  const jsonLd = newsArticleJsonLd({
    url, headline: article.title, description: article.subtitle || article.seo.description,
    images: cover ? [await siteUrl(`/media/${cover.id}/og`), await siteUrl(`/media/${cover.id}/lg`)] : [await siteUrl(assets.social)],
    publishedAt: article.publishedAt, updatedAt: article.updatedAt,
    author: article.author ? { name: article.author.name, url: await pageUrl(locale, { pathname: "/site/author/[id]", params: { id: article.author.id } }) } : null,
    publisher: { name: siteName, logo: await siteUrl(assets.logo), url: await siteUrl(getPathname({ locale, href: "/site" })) },
    section: article.category?.name ?? null, keywords: article.tags.map((tag) => tag.name), language: locale === "pt" ? "pt-BR" : "en",
  });
  const avatar = article.author ? authorAvatarUrl(article.author.id, article.author.avatar) : undefined;
  return <>
    <JsonLd data={jsonLd} />
    <ViewBeacon id={article.id} locale={locale} />
    <div className={styles.progress} style={sectionColor(article.category?.color)} aria-hidden="true" />
    <article className={styles.article} lang={locale === "pt" ? "pt-BR" : "en"} style={sectionColor(article.category?.color)}>
      <header className={styles.articleHeader}>
        {article.breaking
          ? <span className={`${styles.kicker} ${styles.breakingTag}`}>{translate("breaking")}</span>
          : article.category && <Link className={styles.kicker} href={{ pathname: "/site/category/[slug]", params: { slug: article.category.slug } }}>{article.category.name}</Link>}
        <h1 className={styles.articleTitle}>{article.title}</h1>
        {article.subtitle && <p className={styles.articleSubtitle}>{article.subtitle}</p>}
        <div className={styles.byline}>
          <div className={styles.bylineAuthor}>
            {article.author && <Avatar src={avatar} radius="xl" size={44} color="brand" alt="">{article.author.name.charAt(0)}</Avatar>}
            <div>
              {article.author && <div className={styles.bylineName}>{translate("by")} <Link href={{ pathname: "/site/author/[id]", params: { id: article.author.id } }}>{article.author.name}</Link>
                {article.author.jobTitle && <span className={styles.bylineRole}>{article.author.jobTitle}</span>}</div>}
              <div className={styles.meta}>
                <time dateTime={article.publishedAt}>{translate("published", { date: date(article.publishedAt) })}</time>
                {updated && <time dateTime={article.updatedAt}>{translate("updated", { date: date(article.updatedAt) })}</time>}
                <span>{translate("readingTime", { count: article.readingMinutes })}</span>
              </div>
            </div>
          </div>
          <ShareButtons url={url} title={article.title} />
        </div>
      </header>
      {cover && sources && <figure className={styles.cover}>
        {/* eslint-disable-next-line @next/next/no-img-element -- the media library already serves sized WebP renditions (srcset) */}
        <img src={sources.src} srcSet={sources.srcSet} sizes="(min-width: 66em) 1040px, 100vw" alt={cover.alt} width={cover.width} height={cover.height}
          fetchPriority="high" decoding="async" style={{ backgroundColor: cover.color }} />
        {(cover.caption || cover.credit || cover.source === "ai") && <figcaption>
          {cover.caption && <span>{cover.caption}</span>}
          {(cover.source === "ai" || cover.credit) && <span className={styles.coverCredit}>
            {[cover.source === "ai" ? translate("aiImage") : "", cover.credit].filter(Boolean).join(" · ")}
          </span>}
        </figcaption>}
      </figure>}
      <div className={styles.articleColumn}>
        <ArticleBody html={article.body} media={article.media} labels={{ aiImage: translate("aiImage") }} />
        {article.aiAssisted && <p className={styles.aiNote}><Sparkles size={18} aria-hidden="true" style={{ flexShrink: 0, marginTop: 2 }} />{translate("aiAssisted")}</p>}
        {article.tags.length > 0 && <nav className={styles.tags} aria-label={translate("tags")}>
          {article.tags.map((tag) => <Link key={tag.slug} className={styles.chip} href={{ pathname: "/site/tag/[slug]", params: { slug: tag.slug } }}>#{tag.name}</Link>)}
        </nav>}
        <div className={styles.shareFooter}>
          <span>{translate("shareThis")}</span>
          <ShareButtons url={url} title={article.title} />
        </div>
        {article.author && <section className={styles.authorBox} aria-labelledby="about-author">
          <Avatar src={avatar} radius="xl" size={64} color="brand" alt="">{article.author.name.charAt(0)}</Avatar>
          <div>
            <h2 id="about-author">{translate("aboutAuthor")}</h2>
            <Link href={{ pathname: "/site/author/[id]", params: { id: article.author.id } }}>{article.author.name}</Link>
            {article.author.jobTitle && <span className={styles.bylineRole}>{article.author.jobTitle}</span>}
            {article.author.bio && <p>{article.author.bio}</p>}
          </div>
        </section>}
      </div>
    </article>
    {article.related.length > 0 && <section className={styles.related} aria-labelledby="related-heading" style={sectionColor(article.category?.color)}>
      <div className={styles.sectionHeading}><h2 id="related-heading">{translate("related")}</h2></div>
      <div className={`${styles.grid} ${styles.listing}`}>{article.related.map((item) => <NewsCardView key={item.id} item={item} subtitle={false} />)}</div>
    </section>}
  </>;
}
